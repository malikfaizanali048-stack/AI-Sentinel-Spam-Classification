import sys
import joblib
import pandas as pd

sys.path.append("src")
from features.extract_features import extract_all_features
from models.embed_text import load_embedding_model, generate_embeddings

# 1. Load model and get expected feature names using .feature_name()
classifier = joblib.load("data/processed/lgbm_model_enhanced.pkl")

# Booster uses feature_name() method
expected_features = classifier.feature_name()

print("==================================================")
print(f"MODEL EXPECTS {len(expected_features)} FEATURES")
print("First 10 expected features:", expected_features[:10])
print("Last 10 expected features:", expected_features[-10:])
print("==================================================\n")

# 2. Extract features from a sample spam email
test_email = {
    "subject": "URGENT: Your account has been suspended!",
    "body": "Dear customer, your bank account is locked. Click here http://phishing-site.com/login",
    "headers": {},
    "from": "security@fake-bank-alert.com"
}

features = extract_all_features(test_email)
embed_model = load_embedding_model()
embedding = generate_embeddings([f"{test_email['subject']} {test_email['body']}"], embed_model)[0]

# Add embeddings and dummy anomaly score
features["anomaly_score"] = 0.5
emb_dict = {f"emb_{i}": v for i, v in enumerate(embedding)}
features.update(emb_dict)

extracted_keys = list(features.keys())

print("==================================================")
print(f"PIPELINE GENERATED {len(extracted_keys)} FEATURES")
print("First 10 generated features:", extracted_keys[:10])
print("Last 10 generated features:", extracted_keys[-10:])
print("==================================================\n")

# 3. Check for mismatches
missing_in_pipeline = set(expected_features) - set(extracted_keys)
extra_in_pipeline = set(extracted_keys) - set(expected_features)

print("MISMATCH ANALYSIS:")
print(f"Features expected by model but MISSING in pipeline: {len(missing_in_pipeline)}")
if missing_in_pipeline:
    print("  -> Missing:", list(missing_in_pipeline)[:15])

print(f"Features generated by pipeline but NOT in model: {len(extra_in_pipeline)}")
if extra_in_pipeline:
    print("  -> Extra:", list(extra_in_pipeline)[:15])